#Take day number (1–7) and print weekday name.

day_num=input("enter day number :")
if day_num =="1":
    print("monday")
elif day_num=="2":
    print("tuesday")
elif day_num=="3":
    print("wednesday")
elif day_num=="4":
    print("thursday")
elif day_num=="5":
    print("friday")
elif day_num=="6":
    print("saturday")
elif day_num=="7":
    print("sunday")
else: print("invalid number")
