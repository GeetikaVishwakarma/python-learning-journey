# Day 02 - Data Types

# Integer
age = 21

# Float
height = 5.6

# String
name = "Geetika"

# Boolean
is_student = True

# Complex
complex_number = 4 + 5j

print("Integer :", age)
print("Float :", height)
print("String :", name)
print("Boolean :", is_student)
print("Complex :", complex_number)

print()

# Checking data types

print(type(age))
print(type(height))
print(type(name))
print(type(is_student))
print(type(complex_number))

print()

# Type Casting

number = "100"

print(type(number))

number = int(number)

print(number)
print(type(number))

price = 99

price = float(price)

print(price)
print(type(price))